#!/usr/bin/env node
// Import Phosphor icons (https://phosphoricons.com, MIT) as Dainvo Gallery themes.
//
// Usage: node dainvo/tools/import-phosphor.mjs <path-to-extracted-npm-package> [weight]
//   e.g. node dainvo/tools/import-phosphor.mjs /tmp/phosphor/package regular
//
// The package is @phosphor-icons/core from npm. For each theme below this writes:
//   extras/source/gallery/<theme>/*.svg        icons, with currentColor made black
//   extras/source/gallery/<theme>/<theme>.str  name stub (filled from gallery_names.ulf)
//   extras/Gallery_<theme>.mk                  build rule (gengal builds the theme)
// and prints the gallery_names.ulf entries and Module_extras.mk lines to add.
// Re-running replaces the generated files, so it can be used to update Phosphor.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const [pkgDir, weight = "regular"] = process.argv.slice(2);
if (!pkgDir) {
    console.error("usage: import-phosphor.mjs <phosphor package dir> [weight]");
    process.exit(1);
}

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const galleryDir = path.join(repo, "extras/source/gallery");

// Gallery theme id -> display name and the Phosphor primary categories it holds.
// Brand logos are left out on purpose: company logos are trademarks.
const THEMES = [
    ["phosphor-office", "Icons: Office & Education", ["office & editing", "education", "time"]],
    ["phosphor-business", "Icons: Business & Finance", ["commerce", "math & finance"]],
    ["phosphor-arrows", "Icons: Arrows", ["arrows"]],
    ["phosphor-communication", "Icons: Communication", ["communication"]],
    ["phosphor-people", "Icons: People", ["people"]],
    ["phosphor-technology", "Icons: Devices & Technology", ["system & devices", "technology & development"]],
    ["phosphor-design", "Icons: Design", ["design"]],
    ["phosphor-media", "Icons: Media", ["media"]],
    ["phosphor-travel", "Icons: Travel & Places", ["maps & travel"]],
    ["phosphor-nature", "Icons: Nature & Weather", ["weather & nature"]],
    ["phosphor-signs", "Icons: Signs & Security", ["security & warnings"]],
    ["phosphor-leisure", "Icons: Health & Leisure", ["health & wellness", "games"]],
];
const SKIPPED = new Set(["brands"]);

const { icons } = await import(pathToFileURL(path.join(pkgDir, "dist/index.mjs")).href);
const svgDir = path.join(pkgDir, "assets", weight);
const suffix = weight === "regular" ? "" : `-${weight}`;

const byCategory = new Map();
for (const icon of icons) {
    const list = byCategory.get(icon.figma_category) ?? [];
    list.push(icon.name);
    byCategory.set(icon.figma_category, list);
}
const mapped = new Set(THEMES.flatMap(([, , cats]) => cats));
const unmapped = [...byCategory.keys()].filter((c) => !mapped.has(c) && !SKIPPED.has(c));
if (unmapped.length) {
    console.error("Phosphor categories with no theme:", unmapped.join(", "));
    process.exit(1);
}

const LICENSE_HEADER = `# -*- Mode: makefile-gmake; tab-width: 4; indent-tabs-mode: t -*-
#
# This file is part of the LibreOffice project.
#
# This Source Code Form is subject to the terms of the Mozilla Public
# License, v. 2.0. If a copy of the MPL was not distributed with this
# file, You can obtain one at http://mozilla.org/MPL/2.0/.
#
# Generated by dainvo/tools/import-phosphor.mjs - do not edit by hand.
`;

let total = 0;
for (const [id, , cats] of THEMES) {
    const names = cats.flatMap((c) => byCategory.get(c) ?? []).sort();
    const dir = path.join(galleryDir, id);
    fs.rmSync(dir, { recursive: true, force: true });
    fs.mkdirSync(dir, { recursive: true });
    const files = [];
    for (const name of names) {
        const src = path.join(svgDir, `${name}${suffix}.svg`);
        const svg = fs.readFileSync(src, "utf8").replaceAll("currentColor", "#000000");
        fs.writeFileSync(path.join(dir, `${name}.svg`), svg);
        files.push(`\textras/source/gallery/${id}/${name}.svg \\`);
    }
    fs.writeFileSync(
        path.join(dir, `${id}.str`),
        `# Translated by desktop-translate and ulfex\nname = "see extras/source/gallery/share/gallery_names.ulf"\n`
    );
    fs.writeFileSync(
        path.join(repo, `extras/Gallery_${id}.mk`),
        `${LICENSE_HEADER}
$(eval $(call gb_Gallery_Gallery,${id},extras/source/gallery/${id}))

$(eval $(call gb_Gallery_add_files,${id},$(LIBO_SHARE_FOLDER)/gallery/${id},\\
${files.join("\n")}
))

# vim: set noet sw=4 ts=4:
`
    );
    total += names.length;
    console.log(`${String(names.length).padStart(4)}  ${id}`);
}
console.log(`${String(total).padStart(4)}  icons in ${THEMES.length} themes (${weight})\n`);

console.log("gallery_names.ulf entries:");
for (const [id, label] of THEMES) console.log(`[${id}_name]\nen-US = "${label}"\n`);
console.log("Module_extras.mk Gallery targets:");
for (const [id] of THEMES) console.log(`\tGallery_${id} \\`);
